export function translateUI(value, language='zh'){
 if(language!=='zh')return value;
 if(Object.hasOwn(zh,value))return zh[value];
 let m;
 if((m=value.match(/^Page (\d+) of (\d+)$/)))return `第 ${m[1]}／${m[2]} 页`;
 if((m=value.match(/^(\d+) of (\d+) results(?: · Showing (\d+)–(\d+) · Page (\d+) of (\d+))?$/)))return `${m[1]}／${m[2]} 条结果${m[3]?` · 显示 ${m[3]}–${m[4]} 条 · 第 ${m[5]}／${m[6]} 页`:''}`;
 if((m=value.match(/^(\d+) results?$/)))return `${m[1]} 条结果`;
 if((m=value.match(/^(\d+) results? · Page (\d+) of (\d+)$/)))return `${m[1]} 条结果 · 第 ${m[2]}／${m[3]} 页`;
 if((m=value.match(/^Page (\d+)(, current page)?$/)))return `第 ${m[1]} 页${m[2]?'（当前页）':''}`;
 if((m=value.match(/^(.+) \((\d+)\)$/))&&Object.hasOwn(zh,m[1]))return `${zh[m[1]]}（${m[2]}）`;
 if((m=value.match(/^View all (.+) results$/))&&Object.hasOwn(zh,m[1]))return `查看全部${zh[m[1]]}结果`;
 if((m=value.match(/^(\d+) results · page (\d+) of (\d+)$/)))return `${m[1]} 条结果 · 第 ${m[2]}／${m[3]} 页`;
 if((m=value.match(/^Loading full entry…$/)))return '正在加载完整条目…';
 if((m=value.match(/^(\d+) books, lecture notes and papers\. Free-to-read material is selected by default\.$/)))return `${m[1]} 项书籍、讲义与论文。默认显示免费全文资料。`;
 return value;
}

